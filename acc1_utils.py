def _read_cases(text, count_first=True):
    rd = _Reader(text)
    count = rd.int() if count_first else 1
    return [tuple(read_case(rd)) for _ in range(count)]


def _same_output(a, b):
    ta, tb = str(a).split(), str(b).split()
    if len(ta) != len(tb):
        return False
    for x, y in zip(ta, tb):
        if x == y:
            continue
        if FLOAT_TOL is None:
            return False
        try:
            fx, fy = float(x), float(y)
        except ValueError:
            return False
        if abs(fx - fy) > FLOAT_TOL * max(1.0, abs(fy)):
            return False
    return True


