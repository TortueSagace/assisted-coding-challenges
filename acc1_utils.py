class _Reader:
    """Whitespace-token reader over Codeforces-formatted text."""

    def __init__(self, text):
        self.tokens = text.split()
        self.pos = 0

    def str(self):
        token = self.tokens[self.pos]
        self.pos += 1
        return token

    def int(self):
        return int(self.str())

    def float(self):
        return float(self.str())

    def ints(self, k):
        return [self.int() for _ in range(k)]

    def floats(self, k):
        return [self.float() for _ in range(k)]

    def strs(self, k):
        return [self.str() for _ in range(k)]

    def done(self):
        return self.pos >= len(self.tokens)


