def parse_tests(file_path):
    """
    Parse the hidden test file and register the expected answers.

    Returns:
    --------
    list : List of tuples, each tuple being the arguments of my_solution
    """
    with open(file_path, 'r') as f:
        tests = _read_cases(f.read())
    with open(file_path.replace('_tests.txt', '_answers.txt'), 'r') as f:
        answers = [ast.literal_eval(line) for line in f.read().splitlines() if line.strip()]
    if len(answers) != len(tests):
        raise ValueError(f"{len(tests)} tests but {len(answers)} answers")
    _EXPECTED_BY_ID.clear()
    _LOADED[:] = [tests]  # keep the tuples alive so their ids stay unique
    for test, expected in zip(tests, answers):
        _EXPECTED_BY_ID[id(test)] = (deepcopy(test), expected)
    return tests


